param([switch]$Check)
$ErrorActionPreference = 'Stop'
$projectDir = Split-Path $PSScriptRoot -Parent
$coverageRows = @(
    Get-Content -LiteralPath (Join-Path $projectDir 'docs/coverage-system.json') -Raw | ConvertFrom-Json
    Get-Content -LiteralPath (Join-Path $projectDir 'docs/coverage-display.json') -Raw | ConvertFrom-Json
) | Sort-Object page
if ($coverageRows.Count -ne 91 -or @($coverageRows.page | Sort-Object -Unique).Count -ne 91) { throw 'Expected exactly 91 distinct command pages' }
$entries = foreach ($row in $coverageRows) {
    $snapshotPath = Join-Path $projectDir "docs/official/$($row.page).json"
    $article = Get-Content -LiteralPath $snapshotPath -Raw | ConvertFrom-Json
    $opcodeMatch = [regex]::Match($article.page_title,'0x([a-fA-F0-9]+)')
    if (!$opcodeMatch.Success) { throw "No opcode for page $($row.page)" }
    $opcode = '0x{0:X2}' -f [Convert]::ToInt32($opcodeMatch.Groups[1].Value,16)
    $fixturePath = if ($row.page -ge 287 -and $row.page -le 313) { 'tests/display.rs' } else { ($row.tests -split '::')[0] }
    if (!(Test-Path -LiteralPath (Join-Path $projectDir $fixturePath))) { throw "Missing fixture file $fixturePath" }
    $tests = if ($row.tests.StartsWith('tests/')) { $row.tests } else { $fixturePath + '::' + $row.tests }
    $models = switch ([int]$row.page) {
        { $_ -in @(178,179,180,193,194,195,199,200,201,202,203,204,205,206,207,208,209,210,211,212,213,214) } { 'Speaker, SD-card and optional audio hardware families'; break }
        { $_ -ge 246 -and $_ -le 259 } { 'Devices with alarm, memorial or scheduler firmware'; break }
        { $_ -in @(266,272,273,274,275,276,277) } { 'Sleep-scene devices with audio or night lighting'; break }
        { $_ -in @(278,279,280,281) } { 'Matrix games; IDs and key behavior depend on firmware'; break }
        { $_ -in @(297,298,301,302,305,306,307,309,311) } { 'Large64 or multiple-canvas models; no Max compatibility claim'; break }
        { $_ -in @(182,183,184,185,186,191,192) } { 'Clock and weather displays; sensors depend on hardware'; break }
        { $_ -in @(314,315) } { 'Models with ambient-sound control hardware'; break }
        { $_ -in @(289,290,296) } { 'Matrix16 codecs and observed Pixoo-Max32 dialect; indexed save evidence is Max32'; break }
        default { 'Bluetooth matrix family; individual firmware support unverified except stated Max evidence' }
    }
    [ordered]@{page=[int]$row.page;title=$article.page_title;opcode=$opcode;url="https://docin.divoom-gz.com/web/#/5/$($row.page)";snapshot_sha256=(Get-FileHash -LiteralPath $snapshotPath -Algorithm SHA256).Hash.ToLowerInvariant();api=$row.api;tests=$tests;workflow_api=$row.workflow_api;workflow_tests=$row.workflow_tests;device=$models;evidence=$row.evidence;gaps=$row.gaps}
}
if (@($entries.opcode | Sort-Object -Unique).Count -ne 90) { throw 'Expected 90 distinct documented base opcodes' }
$json = ($entries | ConvertTo-Json -Depth 8).Replace("`r`n","`n") + "`n"
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('# Official Bluetooth command coverage')
$lines.Add('')
$lines.Add('Generated by `pwsh -File tools/update-coverage.ps1`. Run it with `-Check` to detect drift.')
$lines.Add('')
$lines.Add('The 91 command pages describe 90 distinct base opcodes. Page 146 describes framing. Every row has a checked payload API and literal fixture. A transport fixture establishes byte encoding, not device compatibility. Unresolved native formats and ambiguous fields are recorded explicitly in the final column and in [protocol gaps](protocol-gaps.md).')
$lines.Add('')
$lines.Add('Max evidence comes from the inherited production 8C capture and reconnect recall observations. This run adds a read-only Windows status test when recorded in [verification](verification.md). Other families have protocol fixtures and no physical test in this repository.')
$lines.Add('')
$lines.Add('| Page and command | Rust API | Fixture | Device evidence and limits |')
$lines.Add('| --- | --- | --- | --- |')
foreach ($e in $entries) {
    $apiText = ($e.api + $(if ($e.workflow_api) {'; '+$e.workflow_api})).Replace('|','\|')
    $fixtureText = $e.tests + $(if ($e.workflow_tests) {'; '+$e.workflow_tests})
    $limitsText = ($e.device + '. ' + $e.evidence + '. ' + $e.gaps).Replace('|','\|').Replace("`n",' ')
    $lines.Add("| [$($e.page) $($e.opcode)]($($e.url)) | $apiText | $fixtureText | $limitsText |")
}
$markdown = ($lines -join "`n") + "`n"
foreach ($output in @(@{name='docs/coverage.json';body=$json},@{name='docs/coverage.md';body=$markdown})) {
    $path = Join-Path $projectDir $output.name
    if ($Check) {
        if (!(Test-Path -LiteralPath $path) -or (Get-Content -LiteralPath $path -Raw).Replace("`r`n","`n") -cne $output.body.Replace("`r`n","`n")) { throw "Coverage drift in $($output.name)" }
    } else { [IO.File]::WriteAllText($path,$output.body,[Text.UTF8Encoding]::new($false)) }
}
Write-Output 'Verified 91 pages, 90 opcodes, source hashes and fixture paths.'
